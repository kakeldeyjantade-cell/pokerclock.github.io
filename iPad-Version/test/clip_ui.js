const { chromium, devices } = require("playwright");
(async () => {
  await fetch("http://localhost:8765/reset", { method: "POST" });
  const b = await chromium.launch(); const errs = [];
  const H = await (await b.newContext({ viewport: { width: 1180, height: 820 } })).newPage();
  H.on("pageerror", (e) => errs.push(e.message));
  await H.goto("http://localhost:8765/#host"); await H.waitForTimeout(3000);
  const C = await (await b.newContext(devices["iPhone 13"])).newPage(); C.on("pageerror", (e) => errs.push(e.message));
  await C.goto("http://localhost:8765/#steuerung"); await C.waitForTimeout(2500);
  await C.click('nav [data-tab="anzeige"]'); await C.waitForTimeout(400);
  console.log("Bausteine in der Liste:", await C.locator("[data-clip]").count());
  await C.click('.clipgrp[data-grp="num"] summary');
  await C.locator('[data-ck="n600"] label.sw').click(); await C.waitForTimeout(1500);
  console.log("auf dem iPad aus:", JSON.stringify(await H.evaluate(() => __host.engine.state.sound.voiceOff)));
  console.log("Zähler:", await C.textContent('.clipgrp[data-grp="num"] .cnt'));
  await C.click('.clipgrp[data-grp="phr"] summary'); await C.waitForTimeout(300);
  await C.locator("#clipCard").screenshot({ path: "v_clips.png" });
  console.log(errs.length ? errs : "keine Fehler");
  await b.close();
})();
