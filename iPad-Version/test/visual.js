const { chromium, devices } = require("playwright");
(async () => {
  await fetch("http://localhost:8765/reset", { method: "POST" });
  const b = await chromium.launch(); const errs = [];
  const ipad = await b.newContext({ viewport: { width: 1180, height: 820 } });
  const H = await ipad.newPage(); H.on("pageerror", (e) => errs.push(e.message));
  await H.goto("http://localhost:8765/?lat=250#host"); await H.waitForTimeout(4500);
  await H.screenshot({ path: "v_qr.png" });
  await H.click(".qr"); await H.click("#dMenuBtn"); await H.waitForTimeout(200); await H.screenshot({ path: "v_menu.png" });
  await H.click("#dmQuick"); await H.waitForTimeout(600); await H.screenshot({ path: "v_quick.png" });
  const ph = await b.newContext({ ...devices["iPhone 13"] });
  const P = await ph.newPage(); P.on("pageerror", (e) => errs.push(e.message));
  await P.goto("http://localhost:8765/?lat=250"); await P.waitForTimeout(800); await P.screenshot({ path: "v_picker_phone.png" });
  await P.click("#bootControl"); await P.waitForTimeout(3000);
  const t0 = Date.now(); await P.click("#bPlay");
  await P.waitForFunction(() => /Pause/.test(document.getElementById("bPlay").textContent), null, { timeout: 9000 });
  console.log("Antwortzeit mit 250 ms Latenz je Weg:", Date.now() - t0, "ms");
  await P.click('nav [data-tab="turnier"]'); await P.waitForTimeout(300); await P.screenshot({ path: "v_ctrl_turnier.png", fullPage: true });
  const off = await b.newContext({ viewport: { width: 1180, height: 820 } });
  const O = await off.newPage(); O.on("pageerror", (e) => errs.push(e.message));
  await O.goto("http://localhost:8765/?nodb&noroom#host"); await O.waitForTimeout(3000);
  console.log("ohne claude.ai:", await O.textContent("#chipConnTxt"), "| Zeit", await O.textContent("#time"));
  await O.click("#main"); await O.click("#dMenuBtn"); await O.click("#dmQuick"); await O.click('[data-q="toggle"]'); await O.waitForTimeout(1500);
  console.log("ohne claude.ai, Schnellsteuerung Start ->", await O.textContent("#time"), await O.textContent("#timeLbl"));
  console.log(errs.length ? errs : "keine Fehler");
  await b.close();
})();
